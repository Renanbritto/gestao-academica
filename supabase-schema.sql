-- 1. TABELA DE PERFIS DE USUÁRIO (profiles)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT DEFAULT 'Monalysa Delvivo Rocha',
  course TEXT DEFAULT 'Direito',
  period TEXT DEFAULT '7º Período',
  target_gpa NUMERIC(5,2) DEFAULT 85.0,
  love_note TEXT DEFAULT 'Bem vinda ao seu painel da facul, boa volta as aulas! ❤️',
  theme TEXT DEFAULT 'dark',
  avatar_data_url TEXT,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABELA DE MATÉRIAS (subjects)
CREATE TABLE IF NOT EXISTS public.subjects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  professor TEXT,
  target_grade NUMERIC(5,2) DEFAULT 85.0,
  color TEXT DEFAULT '#6366f1',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABELA DE ATIVIDADES E PROVAS (activities)
CREATE TABLE IF NOT EXISTS public.activities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  subject_id BIGINT REFERENCES public.subjects(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  type TEXT DEFAULT 'Prova',
  due_date DATE NOT NULL,
  weight NUMERIC(5,2) DEFAULT 25.0,
  max_grade NUMERIC(5,2) DEFAULT 100.0,
  obtained_grade NUMERIC(5,2),
  status TEXT DEFAULT 'Pendente',
  notes TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- =============================================================================
-- HABILITAR ROW LEVEL SECURITY (RLS) - SEGURANÇA POR USUÁRIO
-- =============================================================================
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subjects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activities ENABLE ROW LEVEL SECURITY;

-- POLÍTICAS PARA PROFILES (Cada usuário só lê e edita o seu perfil)
CREATE POLICY "Usuários podem ver seu próprio perfil" 
  ON public.profiles FOR SELECT 
  USING (auth.uid() = id);

CREATE POLICY "Usuários podem atualizar seu próprio perfil" 
  ON public.profiles FOR UPDATE 
  USING (auth.uid() = id);

CREATE POLICY "Usuários podem inserir seu próprio perfil" 
  ON public.profiles FOR INSERT 
  WITH CHECK (auth.uid() = id);

