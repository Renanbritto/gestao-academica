-- =============================================================================
-- TRIGGER AUTOMÁTICO: CRIAR PERFIL INICIAL AO CADASTRAR NOVO USUÁRIO
-- =============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user() 
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, name, course, period, target_gpa, love_note, theme)
  VALUES (
    new.id, 
    COALESCE(new.raw_user_meta_data->>'full_name', 'Monalysa Delvivo Rocha'),
    'Direito',
    '7º Período',
    85.0,
    'Bem vinda ao seu painel da facul, boa volta as aulas! ❤️',
    'dark'
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();
